// ev 图与 gallery 图路径前缀
const pathOf = (name) => name.startsWith("ev-")
  ? `assets/images/events/${name}.jpg`
  : `assets/images/gallery/${name}.jpg`;

let dataJs = fs.readFileSync(DATA, "utf8");

let changed = 0, unchanged = 0;
// 逐个 id 替换 img 字段（匹配 "img:..." 在该事件对象内）
// 事件对象格式: { id:N, ... img:"...", ...}
// 用正则定位每个 id 的 img 字段并替换
for (const [idStr, imgName] of Object.entries(NEW_MAP)) {
  const id = parseInt(idStr);
  const newPath = pathOf(imgName);
  // 匹配 id:N 后到该对象内的 img:"..." (惰性，不跨对象)
  // img 值可能是 "path/a" || "path/b" 形式，整体替换为新路径
  const re = new RegExp(
    "(id:" + id + "[\\s\\S]*?img:\\s*)(?:\"[^\"]*\"(?:\\s*\\|\\|\\s*\"[^\"]*\")*)",
    "g"
  );
  const before = dataJs;
  dataJs = dataJs.replace(re, `$1"${newPath}"`);
  if (dataJs !== before) changed++;
  else {
    console.warn(`⚠ id:${id} 未找到 img 字段，未替换`);
    unchanged++;
  }
}

fs.writeFileSync(DATA, dataJs);
console.log(`\n=== 完成 ===`);
console.log(`已重新分配: ${changed} 个事件`);
console.log(`未匹配: ${unchanged} 个`);

// 统计图片使用分布
const usage = {};
const allMatches = dataJs.match(/img:"assets\/images\/[^"]+"/g) || [];
allMatches.forEach(m => {
  const img = m.replace('img:"', '').replace('"','');
  usage[img] = (usage[img]||0) + 1;
});
console.log(`\n=== 图片使用分布（降序）===`);
Object.entries(usage).sort((a,b)=>b[1]-a[1]).forEach(([k,v])=>{
  console.log(`  ${v}次  ${k}`);
});
